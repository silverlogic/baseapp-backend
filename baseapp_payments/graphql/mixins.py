"""Fields a project's own create mutation mixes in to place a card hold.

::

    class OrderCreate(CardHoldPayloadMixin, RelayMutation):
        class Input(CardHoldPaymentInputMixin):
            ...

        @classmethod
        def mutate_and_get_payload(cls, root, info, **input):
            result = authorize_on_session(...)  # or complete_(setup_)on_session(...)
            return cls(order=result.target, **card_hold_payload(result))
"""

from typing import TYPE_CHECKING, Any

import graphene

if TYPE_CHECKING:
    from ..holds import PlacementResult


class CardHoldPaymentInputMixin:
    payment_method_id = graphene.String(
        description="The Stripe PaymentMethod to hold. Read from Stripe, never trusted."
    )
    attempt_id = graphene.UUID(
        description=(
            "Generated by the client once per checkout and kept across retries and the"
            " authentication second pass: one attempt id places at most one object, and a"
            " retry of a placed attempt returns it. A new attempt id means a new object, so"
            " only renew it after `declined`, `changed` or `refused`."
        )
    )
    payment_intent_id = graphene.String(
        description="The second pass, after authentication: the PaymentIntent to complete."
    )
    setup_intent_id = graphene.String(
        description=(
            "The second pass of a hold placed later, after authentication: the SetupIntent"
            " saving the card, when `intentType` was `setup_intent`."
        )
    )


class CardHoldPayloadMixin:
    requires_action = graphene.Boolean(
        description="Stripe needs the customer to authenticate; confirm `clientSecret`."
    )
    client_secret = graphene.String(
        description="The intent's client secret, when `requiresAction` is true."
    )
    intent_type = graphene.String(
        description="`payment_intent` or `setup_intent`: which intent `clientSecret` is for."
    )
    hold_status = graphene.String(
        description=(
            "How placing ended: placed, scheduled, card_saved (charged on the date, no hold),"
            " charge_now (no hold needed: charge it now), requires_action, declined,"
            " in_progress, changed, amount_changed or refused."
        )
    )
    hold_on = graphene.Date(
        description=(
            "When `holdStatus` is scheduled: the day the card will be held, without the"
            " customer present. Tell the customer."
        )
    )


def card_hold_payload(result: "PlacementResult") -> dict[str, Any]:
    """The payload mixin's values for a placement result."""
    return {
        "requires_action": result.requires_action,
        "client_secret": result.client_secret if result.requires_action else None,
        "intent_type": result.intent_type if result.requires_action else None,
        "hold_status": result.status.value,
        "hold_on": result.hold_on,
    }
